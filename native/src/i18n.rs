    #[test]
    fn test_translations_change_text() {
        let en_general = tr("tab_general", "en");
        let zh_general = tr("tab_general", "zh-CN");
        let ru_general = tr("tab_general", "ru");
        let ja_general = tr("tab_general", "ja");
        let es_general = tr("tab_general", "es");

        assert_eq!(en_general, "General");
        assert_eq!(zh_general, "常规");
        assert_eq!(ru_general, "Основные");
        assert_eq!(ja_general, "一般");
        assert_eq!(es_general, "General");

        assert_ne!(en_general, zh_general);
        assert_ne!(en_general, ru_general);
    }

    #[test]
    fn test_keyboard_layout_alphabet_mapping() {
        // VK for 'Q' is 81
        let ru_q = layout_mapped_char(81, "ru");
        assert_eq!(ru_q.as_deref(), Some("Й"));

        // VK for 'A' is 65
        let ru_a = layout_mapped_char(65, "ru");
        assert_eq!(ru_a.as_deref(), Some("Ф"));

        // Greek: VK for 'A' is 65
        let el_a = layout_mapped_char(65, "el");
        assert_eq!(el_a.as_deref(), Some("Α"));

        // Hebrew: VK for 'T' is 84
        let he_t = layout_mapped_char(84, "he");
        assert_eq!(he_t.as_deref(), Some("א"));

        // Korean: VK for 'Q' is 81
        let ko_q = layout_mapped_char(81, "ko");
        assert_eq!(ko_q.as_deref(), Some("ㅂ"));
    }
