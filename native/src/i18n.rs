/// Returns the keyboard alphabet character for a key press (vk), depending on either:
/// 1) Active operating system layout on Windows, or
/// 2) Selected app language keyboard layout mapping.
pub fn keyboard_alphabet_char(vk: u32, lang: &str) -> Option<String> {
    #[cfg(windows)]
    {
        if let Some(ch) = active_os_keyboard_char(vk) {
            return Some(ch);
        }
    }
    layout_mapped_char(vk, lang)
}

#[cfg(windows)]
fn active_os_keyboard_char(vk: u32) -> Option<String> {
    unsafe {
        use windows_sys::Win32::UI::Input::KeyboardAndMouse::*;
        use windows_sys::Win32::UI::WindowsAndMessaging::*;
        let foreground = GetForegroundWindow();
        let thread_id = if foreground.is_null() {
            0
        } else {
            GetWindowThreadProcessId(foreground, std::ptr::null_mut())
        };
        let layout = GetKeyboardLayout(thread_id);
        if layout.is_null() {
            return None;
        }
        let mut state = [0u8; 256];
        state[VK_CAPITAL as usize] = (GetKeyState(VK_CAPITAL as i32) & 1) as u8;
        let scan = MapVirtualKeyExW(vk, 0, layout);
        let mut chars = [0u16; 8];
        let count = ToUnicodeEx(
            vk,
            scan,
            state.as_ptr(),
            chars.as_mut_ptr(),
            8,
            4,
            layout,
        );
        if count > 0 {
            if let Ok(s) = String::from_utf16(&chars[..count as usize]) {
                if !s.is_empty() && !s.chars().all(|c| c.is_control()) {
                    return Some(s.to_uppercase());
                }
            }
        }
        None
    }
}

